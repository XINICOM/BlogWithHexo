"use strict";

const path = require("path");

if (hexo?.config?.post_asset_folder)
    hexo.extend.filter.register("before_post_render", function (data) {
        if (data.layout !== "post") return data;
        const postName = path.basename(data.source, ".md");
        const imageRegex = /!\[([^\]]*)\]\(([^)]+)\)/g;
        data.content = data.content.replace(imageRegex, (match, alt, src) => {
            if (/^(https?:)?\/\//.test(src) || src.startsWith("/")) return match;
            if (src.startsWith("./")) src = src.slice(2);
            let permalink = data.permalink;
            if (!permalink.endsWith("/")) permalink += "/";
            let basePath = permalink;
            try {
                const url = new URL(permalink, "http://localhost");
                basePath = url.pathname;
            } catch (e) {
                hexo.log.warn(`Img Path Converter CANNOT get the pathname of permalink: ${permalink}`);
                hexo.log.warn("You should carefully check the link generated by this script");
                hexo.log.warn(e);
            }
            if (src.startsWith(postName + "/")) {
                const imagePath = src.substring(postName.length + 1);
                const newSrc = basePath + imagePath;
                hexo.log.info(`Converter Link: ${src} -> ${newSrc}`);
                return `![${alt}](${newSrc})`;
            }
            return match;
        });
        return data;
    });
